    by_slug = {t[0]: t for t in TOPICS}
    assert len(by_slug) == 21, len(by_slug)
    for slug, *rest in TOPICS:
        cfg = build(slug, *rest)
        path = os.path.join(root, f"batch_{slug}.json")
